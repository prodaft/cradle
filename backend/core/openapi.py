"""OpenAPI schema extensions for error responses.

This module provides utilities to automatically document error responses
in the OpenAPI specification generated by DRF Spectacular.
"""

from drf_spectacular.openapi import AutoSchema
from drf_spectacular.utils import OpenApiExample, OpenApiResponse


class CradleAutoSchema(AutoSchema):
    """DRF Spectacular schema that derives tags from app label and trims api_ prefix from operation IDs.

    Used to improve OpenAPI documentation organization and readability.
    """

    def get_tags(self):
        """Derive tags from the view's module (app label) when default is generic."""
        tags = super().get_tags()
        if tags and tags != ["api"]:
            return tags

        module = getattr(self.view, "__module__", "")
        app_label = module.split(".", 1)[0] if module else ""
        if app_label:
            return [app_label.replace("_", "-")]

        return tags

    def get_operation_id(self):
        """Remove leading 'api_' from operation IDs for cleaner schema."""
        operation_id = super().get_operation_id()
        if operation_id.startswith("api_") and len(operation_id) > 4:
            return operation_id[4:]
        return operation_id


# Standard error response schema for OpenAPI documentation
ERROR_RESPONSE_SCHEMA = {
    "type": "object",
    "properties": {
        "type": {
            "type": "string",
            "description": "URI reference identifying the problem type",
            "example": "/errors/validation-error",
        },
        "title": {
            "type": "string",
            "description": "Short, human-readable summary of the problem type",
            "example": "Validation Error",
        },
        "status": {
            "type": "integer",
            "description": "HTTP status code",
            "example": 400,
        },
        "detail": {
            "type": "string",
            "description": "Human-readable explanation specific to this occurrence",
            "example": "One or more fields failed validation.",
        },
        "instance": {
            "type": "string",
            "description": "URI reference identifying the specific occurrence",
            "example": "/api/users/create",
        },
        "timestamp": {
            "type": "string",
            "format": "date-time",
            "description": "ISO 8601 timestamp when the error occurred",
            "example": "2025-11-08T14:32:10.123456Z",
        },
        "code": {
            "type": "string",
            "description": "Machine-readable error code",
            "example": "VALIDATION_ERROR",
        },
        "errors": {
            "type": "object",
            "description": "Field-level validation errors (only present for validation errors)",
            "additionalProperties": {"type": "array", "items": {"type": "string"}},
            "example": {
                "field_name": ["This field is required."],
                "email": ["Enter a valid email address."],
            },
        },
    },
    "required": ["type", "title", "status", "detail", "timestamp", "code"],
}


def _validation_error_example():
    """Build validation error example with field-level errors."""
    from .exceptions import CoreErrorCodes

    code = CoreErrorCodes.VALIDATION_ERROR
    return {
        "type": code.type_uri,
        "title": code.title,
        "status": 400,
        "detail": "One or more fields failed validation.",
        "instance": "/api/example",
        "timestamp": "2025-11-08T14:32:10.123456Z",
        "code": code.code,
        "errors": {
            "field_name": ["This field is required."],
            "email": ["Enter a valid email address."],
        },
    }


def get_error_responses(*error_codes, include_validation_error=False):
    """Generate OpenApiResponse objects for the given error codes.

    This function creates properly formatted OpenAPI response definitions
    that will be included in the API documentation. When multiple error codes
    share the same status code, all are documented as separate examples.

    Args:
        *error_codes: ErrorCode enum values to document.
        include_validation_error: If True, adds VALIDATION_ERROR example with
            field-level errors to 400 response.

    Returns:
        dict: Mapping of status codes to OpenApiResponse objects.

    Example:
        from core.openapi import get_error_responses
        from user.exceptions import UserErrorCodes
        from drf_spectacular.utils import extend_schema

        @extend_schema(
            responses={
                **get_error_responses(
                    UserErrorCodes.DUPLICATE_USER,
                    UserErrorCodes.INVALID_PASSWORD
                )
            }
        )
        def create_user(request):
            ...
    """
    responses = {}
    examples_by_status = {}

    for error_code in error_codes:
        status_code = error_code.status_code
        example = {
            "type": error_code.type_uri,
            "title": error_code.title,
            "status": status_code,
            "detail": error_code.title,
            "instance": "/api/example",
            "timestamp": "2025-11-08T14:32:10.123456Z",
            "code": error_code.code,
        }
        if status_code not in examples_by_status:
            examples_by_status[status_code] = []
        examples_by_status[status_code].append(OpenApiExample(name=error_code.code, value=example, response_only=True))

    if include_validation_error:
        if 400 not in examples_by_status:
            examples_by_status[400] = []
        examples_by_status[400].append(
            OpenApiExample(
                name="VALIDATION_ERROR",
                value=_validation_error_example(),
                response_only=True,
            )
        )

    for status_code, examples in examples_by_status.items():
        descriptions = [e.name for e in examples]
        responses[status_code] = OpenApiResponse(
            response=ERROR_RESPONSE_SCHEMA,
            description="; ".join(descriptions) if len(descriptions) > 1 else descriptions[0],
            examples=examples,
        )

    return responses


def get_common_error_responses():
    """Get common error responses that apply to most authenticated endpoints.

    Returns:
        dict: Common error responses (401, 403, 500).

    Example:
        from core.openapi import get_common_error_responses
        from drf_spectacular.utils import extend_schema

        @extend_schema(
            responses={
                200: MySerializer,
                **get_common_error_responses()
            }
        )
        def my_view(request):
            ...
    """
    from .exceptions import CoreErrorCodes

    return get_error_responses(
        CoreErrorCodes.UNAUTHENTICATED,
        CoreErrorCodes.PERMISSION_DENIED,
        CoreErrorCodes.INTERNAL_SERVER_ERROR,
    )
